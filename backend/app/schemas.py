from __future__ import annotations

import uuid
from datetime import datetime
from typing import Literal

from pydantic import BaseModel, Field, model_validator


class FilmCreate(BaseModel):
    title: str = Field(min_length=1, max_length=200)
    event_type: str = Field(default="other", max_length=40)
    closes_at: datetime
    # Omitted by instant films, which develop the moment they are created.
    reveal_at: datetime | None = None
    # A live album instead of a disposable camera: every shot is visible as soon
    # as it lands. Cannot be changed later; guests cannot un-see a photo.
    instant_reveal: bool = False
    # True (default) is the shared album. False: each guest only sees their own
    # shots. The host inbox and ZIP still hold everything. Can be flipped later,
    # unlike instant_reveal — going private does not un-see a signed URL that
    # already expired, and going shared is a deliberate host action.
    shared_gallery: bool = True
    shot_limit: int = Field(default=24, ge=1, le=500)
    # Requests above the free cap are accepted and then clamped. The host
    # raises the real cap through Checkout, not through this field.
    guest_cap: int = Field(default=5, ge=1, le=1000)
    host_email: str | None = Field(default=None, max_length=254)

    @model_validator(mode="after")
    def _needs_a_reveal_time(self) -> FilmCreate:
        if not self.instant_reveal and self.reveal_at is None:
            raise ValueError("reveal_at is required unless instant_reveal is set")
        return self


class FilmPublic(BaseModel):
    """What anyone holding the code may see.

    Note the absence of any photo field. Before a film develops the API does not
    merely hide URLs, it has nowhere to put them.
    """

    code: str
    title: str
    event_type: str
    closes_at: datetime
    reveal_at: datetime
    is_developed: bool
    is_closed: bool
    shot_limit: int
    guest_cap: int
    entitled_guest_cap: int
    keep_forever: bool
    unlimited_shots: bool
    # Guests may record clips only when this is true.
    video_pack: bool = False
    clips_per_guest: int = 0
    clip_max_seconds: int = 0
    # A live film: shots appear as they are taken, with no reveal to wait for.
    instant_reveal: bool
    # False: gallery URLs are minted only for the calling guest's own shots.
    shared_gallery: bool
    storage_until: datetime
    guest_count: int
    shot_count: int
    # Whether joining needs a PIN. The digits are never sent anywhere; a guest
    # only needs to know that the field should be shown.
    requires_pin: bool
    # Built server-side so the QR code, the host screen and a printed card all
    # encode the same destination.
    join_url: str


class FilmUpdate(BaseModel):
    """Host adjustments while an event is running.

    Caps can be raised freely. They can be lowered only as far as the current
    headcount or the fullest roll, otherwise a paying guest would be stranded.
    """

    closes_at: datetime | None = None
    reveal_at: datetime | None = None
    shot_limit: int | None = Field(default=None, ge=1, le=500)
    guest_cap: int | None = Field(default=None, ge=1, le=1000)
    host_email: str | None = Field(default=None, max_length=254)
    shared_gallery: bool | None = None


class FilmCreated(BaseModel):
    film: FilmPublic
    host_token: str


class JoinRequest(BaseModel):
    display_name: str = Field(min_length=1, max_length=80)
    # Only required when the film carries one. Bounded so a guess costs a
    # request rather than a megabyte of hashing.
    join_pin: str | None = Field(default=None, max_length=20)


class ReportRequest(BaseModel):
    reason: Literal["inappropriate", "private", "other"] = "other"


class ReportResponse(BaseModel):
    shot_id: uuid.UUID
    report_count: int


class PushTokenRequest(BaseModel):
    # Expo's token, not an APNs/FCM blob. Validated as ExpoPushToken[…] so a
    # crafted value cannot turn the worker into an open HTTP client.
    token: str = Field(min_length=20, max_length=200)
    locale: Literal["en", "es", "fr"] = "en"


class SetPinRequest(BaseModel):
    pin: str = Field(min_length=4, max_length=20)


class JoinResponse(BaseModel):
    guest_id: uuid.UUID
    guest_token: str
    display_name: str
    shots_remaining: int
    clips_remaining: int = 0


class ReserveRequest(BaseModel):
    # Generated by the client so retries are idempotent.
    shot_id: uuid.UUID
    content_type: str = Field(default="image/jpeg", max_length=60)
    kind: Literal["photo", "clip"] = "photo"


class ReserveResponse(BaseModel):
    shot_id: uuid.UUID
    upload_url: str
    storage_key: str
    expires_in: int
    already_reserved: bool
    shots_remaining: int
    clips_remaining: int = 0
    # Echoed so the client PUTs with exactly the type the URL was signed for.
    content_type: str = "image/jpeg"


class CommitResponse(BaseModel):
    shot_id: uuid.UUID
    state: str
    shots_remaining: int
    clips_remaining: int = 0


class GalleryPhoto(BaseModel):
    shot_id: uuid.UUID
    guest_name: str
    uploaded_at: datetime | None
    # For a clip, the transcoded MP4. poster_url is its still frame.
    url: str
    kind: Literal["photo", "clip"] = "photo"
    poster_url: str | None = None
    duration_ms: int | None = None
    # Screen-sized photo once the worker has made it. A slideshow uses this so
    # a projector is not pulling 25 MB originals every few seconds.
    display_url: str | None = None


class GalleryResponse(BaseModel):
    is_developed: bool
    shot_count: int
    photos: list[GalleryPhoto]


class ReviewPhoto(BaseModel):
    shot_id: uuid.UUID
    guest_name: str
    uploaded_at: datetime | None
    hidden: bool
    # How many guests flagged this. Never who: a report must not start an
    # argument between two people at the same wedding.
    report_count: int = 0
    url: str
    kind: Literal["photo", "clip"] = "photo"
    poster_url: str | None = None
    duration_ms: int | None = None
    display_url: str | None = None


class ReviewResponse(BaseModel):
    """Host-only. Signed URLs exist here even before the film develops."""

    shot_count: int
    hidden_count: int
    # Reported and still visible, i.e. the ones actually waiting on the host.
    reported_count: int = 0
    photos: list[ReviewPhoto]


