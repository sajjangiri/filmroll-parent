class PaymentReceipt(BaseModel):
    """Host-only. One line on the receipts list.

    ``amount_cents`` is the catalog price and ``total_cents`` is what Stripe
    captured; they differ by ``tax_cents`` wherever we collect VAT or sales tax.
    """

    id: uuid.UUID
    kind: str
    label: str
    status: str
    amount_cents: int
    tax_cents: int
    total_cents: int
    refunded_cents: int
    currency: str
    receipt_url: str | None
    customer_email: str | None
    created_at: datetime
    paid_at: datetime | None
    refunded_at: datetime | None


class PaymentsResponse(BaseModel):
    payments: list[PaymentReceipt]
    total_paid_cents: int
    total_tax_cents: int
    total_refunded_cents: int
    currency: str


