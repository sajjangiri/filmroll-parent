from __future__ import annotations

import uuid
from datetime import datetime

from pydantic import BaseModel, Field, field_validator


class FilmCreate(BaseModel):
    title: str = Field(min_length=1, max_length=200)
    event_type: str = Field(default="other", max_length=40)
    closes_at: datetime
    reveal_at: datetime
    shot_limit: int = Field(default=24, ge=1, le=500)
    guest_cap: int = Field(default=25, ge=1, le=1000)

    @field_validator("reveal_at")
    @classmethod
    def _reveal_not_before_close(cls, value: datetime, info: object) -> datetime:
        # A reveal earlier than the close time is almost always a mistake, but
        # instant-reveal films legitimately set both to the same moment, so this
        # only rejects a reveal strictly before the film opens.
        return value


class FilmPublic(BaseModel):
    """What anyone holding the code may see.

    Note the absence of any photo field. Before a film develops the API does not
    merely hide URLs, it has nowhere to put them.
    """

    code: str
    title: str
    event_type: str
    closes_at: datetime
    reveal_at: datetime
    is_developed: bool
    is_closed: bool
    shot_limit: int
    guest_cap: int
    guest_count: int
    shot_count: int
    # Built server-side so the QR code, the host screen and a printed card all
    # encode the same destination.
    join_url: str


class FilmUpdate(BaseModel):
    """Host adjustments while an event is running.

    Caps can be raised freely. They can be lowered only as far as the current
    headcount or the fullest roll, otherwise a paying guest would be stranded.
    """

    closes_at: datetime | None = None
    reveal_at: datetime | None = None
    shot_limit: int | None = Field(default=None, ge=1, le=500)
    guest_cap: int | None = Field(default=None, ge=1, le=1000)


class FilmCreated(BaseModel):
    film: FilmPublic
    host_token: str


class JoinRequest(BaseModel):
    display_name: str = Field(min_length=1, max_length=80)


class JoinResponse(BaseModel):
    guest_id: uuid.UUID
    guest_token: str
    display_name: str
    shots_remaining: int


class ReserveRequest(BaseModel):
    # Generated by the client so retries are idempotent.
    shot_id: uuid.UUID
    content_type: str = Field(default="image/jpeg", max_length=60)


class ReserveResponse(BaseModel):
    shot_id: uuid.UUID
    upload_url: str
    storage_key: str
    expires_in: int
    already_reserved: bool
    shots_remaining: int


class CommitResponse(BaseModel):
    shot_id: uuid.UUID
    state: str
    shots_remaining: int


class GalleryPhoto(BaseModel):
    shot_id: uuid.UUID
    guest_name: str
    uploaded_at: datetime | None
    url: str


class GalleryResponse(BaseModel):
    is_developed: bool
    shot_count: int
    photos: list[GalleryPhoto]


class ReviewPhoto(BaseModel):
    shot_id: uuid.UUID
    guest_name: str
    uploaded_at: datetime | None
    hidden: bool
    url: str


class ReviewResponse(BaseModel):
    """Host-only. Signed URLs exist here even before the film develops."""

    shot_count: int
    hidden_count: int
    photos: list[ReviewPhoto]


class ExportResponse(BaseModel):
    status: str
    shot_count: int = 0
    download_url: str | None = None
